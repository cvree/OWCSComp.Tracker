/* Beta Ops dashboard — reads the small, non-sensitive, committed
   assets/data/job_coverage.v1.json (generated by
   `pipeline/automation/cli.py job-coverage --save`). Read-only: every
   listed action is a CLI command an operator runs themselves — this static
   page never calls back into a server (GitHub Pages has none). Job
   payloads carry only match/team/video ids and public broadcast URLs,
   nothing secret. */
(function () {
  "use strict";
  const esc = (s) => String(s == null ? "" : s).replace(/[&<>"']/g, (c) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

  const OK_STATES = new Set(["PUBLISHED", "APPROVED", "DOWNLOADED"]);
  const WARN_STATES = new Set(["NEEDS_REVIEW", "RETRY_SCHEDULED", "SEGMENTING", "PROCESSING"]);
  const BAD_STATES = new Set(["FAILED_PERMANENT", "FAILED", "CANCELLED"]);

  function stateChip(s) {
    const cls = OK_STATES.has(s) ? "ok" : BAD_STATES.has(s) ? "bad"
      : WARN_STATES.has(s) ? "warn" : "";
    return `<span class="cov-state ${cls}">${esc(s)}</span>`;
  }

  // One CLI command suggestion per recommended next action, so an operator
  // never has to guess the right subcommand or flags.
  function commandFor(job) {
    const key = esc(job.jobKey);
    const map = {
      "run the worker (download)": `worker-run --worker-id <id>`,
      "wait, or resume if the worker crashed": `resume-job --worker-id <id>`,
      "generate segment candidates": `run-job ${key} --worker-id <id>`,
      "wait for candidate generation": null,
      "open segment or detection review in the control room":
        `segment-list --video-id ${esc(job.videoId)}`,
      "run detection": `detect-job ${key}`,
      "wait for detection to finish": null,
      "commit detection, then publish when ready":
        `detect-job ${key} --write   # then: process-approved-job --job ${key} --publish`,
      "confirm PR merged and Pages deployed": null,
      "wait for the scheduled retry, or retry now": `retry-job ${key}`,
      "investigate the dead-letter, then force-retry if fixed": `retry-job ${key} --force`,
      "none — job was explicitly cancelled": null,
    };
    const cmd = map[job.nextAction];
    return cmd ? `python pipeline/automation/cli.py ${cmd}` : null;
  }

  function row(j) {
    const cmd = commandFor(j);
    return `<tr>
      <td><strong>${esc(j.match || "(no match)")}</strong>
          <div class="muted small">${esc(j.teamA)} vs ${esc(j.teamB)}</div></td>
      <td>${esc(j.jobKey)}</td>
      <td>${stateChip(j.state)}</td>
      <td>${esc(j.workerId || "—")}</td>
      <td>${j.attempts}</td>
      <td>${j.lastErrorCode ? `<span class="cov-blocking">[${esc(j.lastErrorCode)}] ${esc(j.lastErrorMessage)}</span>` : '<span class="cov-none">—</span>'}</td>
      <td><span class="cov-action">${esc(j.nextAction)}</span>
          ${cmd ? `<code class="cov-cmd">${esc(cmd)}</code>` : ""}</td>
    </tr>`;
  }

  function render(report) {
    const summary = document.getElementById("cov-summary");
    summary.innerHTML = [
      `<span><b>${report.totalJobs}</b> job(s) tracked</span>`,
      `<span><b>${report.recentlyUpdated}</b> updated in the last ${report.windowHours}h</span>`,
      `<span><b>${report.blocked.length}</b> blocked</span>`,
      `<span>generated <b>${esc(report.generatedAt)}</b></span>`,
      ...Object.entries(report.countsByState || {}).map(([k, n]) =>
        `<span><b>${n}</b> ${esc(k)}</span>`),
    ].join("");

    const root = document.getElementById("cov-root");
    const jobs = report.jobs || [];
    if (!jobs.length) {
      root.innerHTML = `<p class="muted">No jobs yet — create one with
        <code>python pipeline/automation/cli.py create-job --match &lt;id&gt; --video-id &lt;id&gt; --source-url &lt;url&gt; --channel-id &lt;id&gt; --team-a &lt;id&gt; --team-b &lt;id&gt;</code>.</p>`;
      return;
    }
    root.innerHTML = `
      <table class="cov-tbl">
        <thead><tr><th>Match</th><th>Job</th><th>State</th><th>Worker</th>
            <th>Attempts</th><th>Last error</th><th>Recommended next action</th></tr></thead>
        <tbody>${jobs.map(row).join("")}</tbody>
      </table>`;
  }

  fetch("assets/data/job_coverage.v1.json")
    .then((r) => { if (!r.ok) throw new Error(`HTTP ${r.status}`); return r.json(); })
    .then(render)
    .catch((err) => {
      document.getElementById("cov-root").innerHTML =
        `<p class="muted">Could not load job_coverage.v1.json (${esc(err.message)}). ` +
        `Run <code>pipeline/automation/cli.py job-coverage --save</code> to generate it, ` +
        `or serve this page over http(s) rather than file://.</p>`;
    });
})();
