/* Team Coverage ops dashboard — reads the small, non-sensitive, committed
   assets/data/team_coverage.v1.json (generated by
   `pipeline/automation/cli.py team-coverage --save`). Every field here is
   already public (team names/regions/coverage states); nothing secret. */
(function () {
  "use strict";
  const esc = (s) => String(s == null ? "" : s).replace(/[&<>"']/g, (c) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

  const OK_STATES = new Set(["identity-verified", "roster-verified", "logo-verified",
    "broadcast-located", "composition-captured"]);
  const WARN_STATES = new Set(["needs-review", "unsupported", "logo-candidate"]);

  function stateChip(s) {
    const cls = OK_STATES.has(s) ? "ok" : WARN_STATES.has(s) ? "warn" : "";
    return `<span class="cov-state ${cls}">${esc(s)}</span>`;
  }

  function row(t) {
    return `<tr>
      <td><strong>${esc(t.name)}</strong><div class="muted small">${esc(t.id)}</div></td>
      <td>${esc(t.region)}</td>
      <td>${esc(t.status)}</td>
      <td>${(t.states || []).map(stateChip).join("") || '<span class="cov-none">none</span>'}</td>
      <td>${t.matches}</td>
      <td>${t.broadcastsLocated}</td>
      <td>${t.capturedMaps}</td>
      <td>${t.blockingIssue ? `<span class="cov-blocking">${esc(t.blockingIssue)}</span>` : '<span class="cov-none">—</span>'}</td>
    </tr>`;
  }

  function render(report) {
    const c = report.counts || {};
    const summary = document.getElementById("cov-summary");
    summary.innerHTML = [
      `<span><b>${report.teams.length}</b> teams tracked</span>`,
      `<span>rolling <b>${report.window_days}</b>-day window</span>`,
      `<span>generated <b>${esc(report.generated_at)}</b></span>`,
      ...Object.entries(c).filter(([, n]) => n).map(([k, n]) =>
        `<span><b>${n}</b> ${esc(k.replace(/_/g, "-"))}</span>`),
    ].join("");

    const root = document.getElementById("cov-root");
    if (!report.teams.length) {
      root.innerHTML = `<p class="muted">No teams in the registry yet — run a discovery sync first.</p>`;
      return;
    }
    root.innerHTML = `<table class="cov-tbl">
      <tr><th>Team</th><th>Region</th><th>Status</th><th>Coverage</th>
          <th>Matches</th><th>Broadcasts</th><th>Captured maps</th><th>Blocking issue</th></tr>
      ${report.teams.map(row).join("")}
    </table>`;
  }

  fetch("assets/data/team_coverage.v1.json")
    .then((r) => { if (!r.ok) throw new Error(`HTTP ${r.status}`); return r.json(); })
    .then(render)
    .catch((err) => {
      document.getElementById("cov-root").innerHTML =
        `<p class="muted">Could not load team_coverage.v1.json (${esc(err.message)}). ` +
        `Run <code>pipeline/automation/cli.py team-coverage --save</code> to generate it, ` +
        `or serve this page over http(s) rather than file://.</p>`;
    });
})();
