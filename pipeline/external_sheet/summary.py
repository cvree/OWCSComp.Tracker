"""
summary.py — two small companions to the public spreadsheet export.

external_sheet.v1.js is over 2 MB: every map, every listing, the whole
reconciliation. Most pages need a fraction of it, so the exporter also
writes two derived files from the SAME payload, in the same run:

  assets/data/external_summary.v1.js   window.OWCS_EXTERNAL_SUMMARY
      headline totals, coverage per region and stage, per-hero listing
      and ban counts (overall / by region / by stage), per-team profiles,
      the unmapped values, the snapshot and credit. Loaded by the home
      page, Comps, the hero page and the team directory.

  assets/data/external_series.v1.js    window.OWCS_EXTERNAL_SERIES
      one row per series (teams, format, series score, maps with winner
      side) in the sheet's own order, plus the reconciliation records
      that have a VOD link or candidate. Loaded by the series list and
      the series page, which fetch one map's player listings from the
      detail shards on demand.

Every number here is a SPREADSHEET observation and stays one: nothing is
read from or added to the VOD dataset. Rules carried over from the main
export (docs/EXTERNAL-SHEET.md):

  * a listed hero is an appearance (the map lists it), never playtime;
  * a ban counts only when its hero resolved; unresolved text is counted
    as unresolved, never guessed;
  * a map whose winner the VOD reading disputes (reconciliation field
    `winner.agree is False`) is left out of every win count and counted
    as disputed; a map with no resolved winner is "undecided";
  * maps the operator ignored are already absent from the payload;
  * the sheet has no dates and no map picks, so nothing here has either.
    Order is the sheet's own: stage of the season, then week/day/game.

Pure functions of the payload: `sheet_sync.py check` rebuilds both files
and fails on drift, exactly like the main export.
"""
from __future__ import annotations

import json
from collections import Counter, defaultdict

SUMMARY_SCHEMA = "external-summary.v1"
SERIES_SCHEMA = "external-series.v1"

# The season's stages in the order they are played. A stage key not listed
# sorts after these, alphabetically. Mirrored by STAGE_ORDER in
# assets/js/app/extstats.js and assets/js/app/metastats.js (a test keeps
# the three equal).
STAGE_ORDER = ["pre-season", "stage-1", "champions-clash", "stage-2",
               "midseason-championship", "stage-3", "world-finals"]
REGION_ORDER = ["na", "emea", "korea", "japan", "china", "pacific", "asia", "international"]

SUMMARY_HEADER = """/* =====================================================================
   OWCS Comp Tracker — external_summary.v1.js  (IMPORTED community spreadsheet)
   GENERATED by pipeline/sheet_sync.py from the same payload as
   external_sheet.v1.js — do not hand-edit. Aggregates of spreadsheet
   observations only: counts of listed heroes and bans, records and
   coverage. Never timed, never blended with VOD numbers.
   Contract: docs/EXTERNAL-SHEET.md
   ===================================================================== */
window.OWCS_EXTERNAL_SUMMARY = """

SERIES_HEADER = """/* =====================================================================
   OWCS Comp Tracker — external_series.v1.js  (IMPORTED community spreadsheet)
   GENERATED by pipeline/sheet_sync.py — do not hand-edit. One row per
   series the sheet documents, in the sheet's own order (stage, week,
   day, game). The sheet records no dates and no map picks.
   Contract: docs/EXTERNAL-SHEET.md
   ===================================================================== */
window.OWCS_EXTERNAL_SERIES = """


def stage_rank(stage: str | None) -> int:
    if stage in STAGE_ORDER:
        return STAGE_ORDER.index(stage)
    return len(STAGE_ORDER)


def region_rank(region: str | None) -> int:
    if region in REGION_ORDER:
        return REGION_ORDER.index(region)
    return len(REGION_ORDER) + (0 if region else 1)


def series_key(m: dict) -> tuple:
    """The sheet's own order for a series: stage of the season, region,
    week, day, game. Not a date and never turned into one."""
    num = lambda v: v if isinstance(v, int) else 999  # noqa: E731
    return (m.get("year") or 0, stage_rank(m.get("stageKey") or m.get("stage")), m.get("stageKey") or "",
            region_rank(m.get("region")), num(m.get("week")), num(m.get("day")), num(m.get("game")),
            m.get("id") or "")


def _disputed(rec: dict | None) -> bool:
    w = ((rec or {}).get("fields") or {}).get("winner") or {}
    return w.get("agree") is False


def _top(counter: Counter, n: int) -> list:
    return [[k, v] for k, v in sorted(counter.items(), key=lambda kv: (-kv[1], kv[0]))[:n]]


def _credits(payload: dict) -> list:
    seen, out = set(), []
    for c in (payload.get("source") or {}).get("creditsFound") or []:
        text = (c.get("text") or "").strip()
        if text and text not in seen:
            seen.add(text)
            out.append({"sheet": c.get("sheet"), "cell": c.get("cell"), "text": text})
    return out


# ------------------------------------------------------------------ summary
def build_summary(payload: dict) -> dict:
    matches = {m["id"]: m for m in payload.get("matches") or []}
    maps = payload.get("maps") or []
    recon = payload.get("reconciliation") or {}
    recs = {r["externalMapId"]: r for r in recon.get("records") or []}
    team_names = payload.get("teams") or {}

    # ---------------------------------------------------------- coverage
    cov: dict[tuple, dict] = {}

    def cov_row(m: dict) -> dict:
        k = (m.get("stageKey") or m.get("stage"), m.get("region"))
        if k not in cov:
            cov[k] = {"stage": k[0], "stageRaw": m.get("stageRaw"), "region": k[1],
                      "event": m.get("event"), "tournamentId": m.get("tournamentId"),
                      "matches": 0, "maps": 0, "bans": 0, "listings": 0}
        return cov[k]

    for m in matches.values():
        cov_row(m)["matches"] += 1

    # ------------------------------------------------------------ heroes
    hero_all: dict[str, list] = defaultdict(lambda: [0, 0, 0, 0])   # listedMaps, listedSides, bans, banMaps
    # per slice: [listedMaps, bans, banMaps]
    hero_region: dict[str, dict] = defaultdict(lambda: defaultdict(lambda: [0, 0, 0]))
    hero_stage: dict[str, dict] = defaultdict(lambda: defaultdict(lambda: [0, 0, 0]))
    den = {"all": {"maps": 0, "banMaps": 0, "sides": 0},
           "region": defaultdict(lambda: {"maps": 0, "banMaps": 0}),
           "stage": defaultdict(lambda: {"maps": 0, "banMaps": 0})}

    # ------------------------------------------------------------- teams
    def new_team(tid: str) -> dict:
        t = team_names.get(tid) or {"name": tid, "mapped": False}
        return {"id": tid, "name": t.get("name") or tid, "mapped": bool(t.get("mapped")),
                "regions": set(), "stages": set(),
                "series": {"played": 0, "won": 0, "lost": 0, "undecided": 0},
                "maps": {"played": 0, "won": 0, "lost": 0, "draw": 0, "undecided": 0, "disputed": 0,
                         "listed": 0, "banned": 0},
                "byMap": defaultdict(lambda: [0, 0, 0, 0]), "byMode": defaultdict(lambda: [0, 0, 0, 0]),
                "heroes": Counter(), "bansBy": Counter(), "bansAgainst": Counter()}
    teams: dict[str, dict] = {}

    def team(tid: str) -> dict:
        if tid not in teams:
            teams[tid] = new_team(tid)
        return teams[tid]

    for m in matches.values():
        for side, opp in (("teamA", "teamB"), ("teamB", "teamA")):
            tid = m.get(side)
            if not tid:
                continue
            t = team(tid)
            if m.get("region"):
                t["regions"].add(m["region"])
            if m.get("stageKey") or m.get("stage"):
                t["stages"].add(m.get("stageKey") or m.get("stage"))
            t["series"]["played"] += 1
            if m.get("winner") and m.get("seriesComplete") is not False:
                t["series"]["won" if m["winner"] == tid else "lost"] += 1
            else:
                t["series"]["undecided"] += 1

    totals = Counter({k: 0 for k in ("maps", "undatedMaps", "mapsWithPick", "linkedMaps", "bans",
                                     "resolvedBans", "listings", "unresolvedListings")})
    for mp in maps:
        m = matches.get(mp.get("matchId")) or {}
        stage = m.get("stageKey") or m.get("stage")
        region = m.get("region")
        rec = recs.get(mp["id"])
        row = cov_row(m) if m else None
        totals["maps"] += 1
        if not mp.get("date"):
            totals["undatedMaps"] += 1
        if mp.get("pickedBy"):
            totals["mapsWithPick"] += 1
        if rec and rec.get("vodMapId"):
            totals["linkedMaps"] += 1
        bans = mp.get("bans") or []
        resolved_bans = [b for b in bans if b.get("hero")]
        totals["bans"] += len(bans)
        totals["resolvedBans"] += len(resolved_bans)
        sides = (mp.get("teams") or {})
        listed_any = False
        heroes_on_map: set[str] = set()
        for s in ("a", "b"):
            st = sides.get(s) or {}
            totals["listings"] += st.get("listed") or 0
            totals["unresolvedListings"] += st.get("unresolved") or 0
            hs = st.get("heroes") or []
            if hs:
                listed_any = True
                den["all"]["sides"] += 1
            for h in hs:
                hero_all[h][1] += 1
                heroes_on_map.add(h)
        if row is not None:
            row["maps"] += 1
            row["bans"] += len(bans)
            row["listings"] += sum((sides.get(s) or {}).get("listed") or 0 for s in ("a", "b"))
        if listed_any:
            den["all"]["maps"] += 1
            den["region"][region or "none"]["maps"] += 1
            den["stage"][stage or "none"]["maps"] += 1
            for h in heroes_on_map:
                hero_all[h][0] += 1
                hero_region[h][region or "none"][0] += 1
                hero_stage[h][stage or "none"][0] += 1
        if bans:
            den["all"]["banMaps"] += 1
            den["region"][region or "none"]["banMaps"] += 1
            den["stage"][stage or "none"]["banMaps"] += 1
        banned_here: set[str] = set()
        for b in resolved_bans:
            h = b["hero"]
            hero_all[h][2] += 1
            hero_region[h][region or "none"][1] += 1
            hero_stage[h][stage or "none"][1] += 1
            banned_here.add(h)
        for h in banned_here:
            hero_all[h][3] += 1
            hero_region[h][region or "none"][2] += 1
            hero_stage[h][stage or "none"][2] += 1

        # team lanes
        disputed = _disputed(rec)
        for s, tid, opp in (("a", mp.get("teamA"), mp.get("teamB")), ("b", mp.get("teamB"), mp.get("teamA"))):
            if not tid:
                continue
            t = team(tid)
            t["maps"]["played"] += 1
            key = mp.get("map") or ("?" + (mp.get("mapRaw") or "unknown"))
            mode = mp.get("mode") or "?"
            by_map, by_mode = t["byMap"][key], t["byMode"][mode]
            by_map[0] += 1
            by_mode[0] += 1
            if disputed:
                t["maps"]["disputed"] += 1
            elif mp.get("winnerSide") == "draw":
                t["maps"]["draw"] += 1
                by_map[3] += 1
                by_mode[3] += 1
            elif mp.get("winnerSide") in ("a", "b"):
                won = mp["winnerSide"] == s
                t["maps"]["won" if won else "lost"] += 1
                by_map[1 if won else 2] += 1
                by_mode[1 if won else 2] += 1
            else:
                t["maps"]["undecided"] += 1
            hs = (sides.get(s) or {}).get("heroes") or []
            if hs:
                t["maps"]["listed"] += 1
            t["heroes"].update(hs)
            if bans:
                t["maps"]["banned"] += 1
            for b in resolved_bans:
                if b.get("teamId") == tid:
                    t["bansBy"][b["hero"]] += 1
                elif b.get("teamId") == opp:
                    t["bansAgainst"][b["hero"]] += 1

    summ = recon.get("summary") or {}
    totals["matches"] = len(matches)
    totals["teams"] = len(teams)
    totals["unmappedTeams"] = sum(1 for t in teams.values() if not t["mapped"])
    totals["sheetOnlyMaps"] = totals["maps"] - totals["linkedMaps"]
    totals["conflict"] = summ.get("conflict", 0)
    totals["needsReview"] = summ.get("needs_review", 0)

    coverage = sorted(cov.values(), key=lambda r: (stage_rank(r["stage"]), r["stage"] or "",
                                                  region_rank(r["region"])))
    heroes_out = {}
    for h in sorted(hero_all):
        a = hero_all[h]
        heroes_out[h] = {"listedMaps": a[0], "listedSides": a[1], "bans": a[2], "banMaps": a[3],
                         "region": {k: v for k, v in sorted(hero_region[h].items())},
                         "stage": {k: v for k, v in sorted(hero_stage[h].items())}}
    teams_out = {}
    for tid in sorted(teams):
        t = teams[tid]
        teams_out[tid] = {
            "id": tid, "name": t["name"], "mapped": t["mapped"],
            "regions": sorted(t["regions"], key=region_rank),
            "stages": sorted(t["stages"], key=lambda s: (stage_rank(s), s)),
            "series": t["series"], "maps": t["maps"],
            "byMap": {k: v for k, v in sorted(t["byMap"].items(), key=lambda kv: (-kv[1][0], kv[0]))},
            "byMode": {k: v for k, v in sorted(t["byMode"].items(), key=lambda kv: (-kv[1][0], kv[0]))},
            "heroes": _top(t["heroes"], 15),
            "bansBy": _top(t["bansBy"], 10), "bansAgainst": _top(t["bansAgainst"], 10),
        }
    health = payload.get("health") or {}
    unmapped = {k: [{"raw": r.get("raw"), "count": r.get("count")} for r in (v or [])[:12]]
                for k, v in (health.get("unmapped") or {}).items() if k in ("hero", "map", "team")}
    snap = payload.get("snapshot") or {}
    src = payload.get("source") or {}
    meta = payload.get("meta") or {}
    return {
        "meta": {"schema": SUMMARY_SCHEMA, "status": meta.get("status"), "fixture": meta.get("fixture"),
                 "fixtureNote": meta.get("fixtureNote"), "note": meta.get("note"),
                 "provenanceLabels": meta.get("provenanceLabels"),
                 "derivedFrom": "assets/data/external_sheet.v1.js",
                 "rules": ["listed heroes are appearances, never playtime",
                           "appearance rate = maps where the hero is listed / maps with any listing",
                           "ban rate = maps where the hero is banned / maps with a ban recorded",
                           "a winner the VOD reading disputes is excluded from win counts",
                           "no dates and no map picks: the sheet records neither"]},
        "source": {"label": src.get("label"), "viewUrl": src.get("viewUrl"),
                   "maintainer": src.get("maintainer"), "creditNote": src.get("creditNote"),
                   "credits": _credits(payload)},
        "snapshot": {k: snap.get(k) for k in ("sha256", "importedAt", "parserVersion")} if snap else None,
        "lastAttempt": payload.get("lastAttempt"),
        "stageOrder": STAGE_ORDER,
        "regionOrder": REGION_ORDER,
        "teams": {tid: {"id": tid, "name": v.get("name"), "mapped": v.get("mapped")}
                  for tid, v in sorted(team_names.items())},
        "mapsExtra": payload.get("mapsExtra") or {},
        "totals": dict(sorted(totals.items())),
        # Every spreadsheet map that has a VOD link or candidate, so a VOD
        # game page can say "also in the spreadsheet" without the full file.
        "links": [{"externalMapId": r["externalMapId"], "vodMapId": r.get("vodMapId"),
                   "status": r.get("status"),
                   "matchId": (next((m for m in maps if m["id"] == r["externalMapId"]), {}) or {}).get("matchId"),
                   "candidates": [c.get("vodMapId") for c in r.get("candidates") or []]}
                  for r in recon.get("records") or [] if r.get("vodMapId") or r.get("candidates")],
        "reconciliation": summ,
        "coverage": coverage,
        "heroDenominators": {"all": den["all"],
                             "region": {k: v for k, v in sorted(den["region"].items())},
                             "stage": {k: v for k, v in sorted(den["stage"].items())}},
        "heroes": heroes_out,
        "teamProfiles": teams_out,
        "unmapped": unmapped,
    }


# ------------------------------------------------------------------- series
def build_series(payload: dict) -> dict:
    maps = {m["id"]: m for m in payload.get("maps") or []}
    recon = payload.get("reconciliation") or {}
    recs = {r["externalMapId"]: r for r in recon.get("records") or []}
    rows = []
    for m in sorted(payload.get("matches") or [], key=series_key):
        mlist = []
        for mid in m.get("mapIds") or []:
            mp = maps.get(mid)
            if not mp:
                continue                      # ignored by an operator decision
            e = {"id": mid, "n": mp.get("order"), "map": mp.get("map"), "w": mp.get("winnerSide")}
            if not mp.get("map"):
                e["raw"] = mp.get("mapRaw")
            rec = recs.get(mid)
            if rec and rec.get("status") != "unmatched":
                e["rec"] = rec["status"]
            mlist.append(e)
        mlist.sort(key=lambda e: (e["n"] if isinstance(e["n"], int) else 99, e["id"]))
        rows.append({
            "id": m["id"], "region": m.get("region"), "stage": m.get("stageKey") or m.get("stage"),
            "stageRaw": m.get("stageRaw"), "event": m.get("event"), "tournamentId": m.get("tournamentId"),
            "year": m.get("year"), "week": m.get("week"), "day": m.get("day"), "game": m.get("game"),
            "label": m.get("gameLabel"), "format": m.get("format"), "bestOf": m.get("bestOf"),
            "teamA": m.get("teamA"), "teamB": m.get("teamB"),
            "scoreA": m.get("seriesScoreA"), "scoreB": m.get("seriesScoreB"),
            "complete": m.get("seriesComplete"), "winner": m.get("winner"),
            "potm": m.get("playerOfTheMatchRaw"), "flags": m.get("flags") or [],
            "src": m.get("src"), "maps": mlist,
        })
    records = [r for r in recon.get("records") or [] if r.get("vodMapId") or r.get("candidates")]
    snap = payload.get("snapshot") or {}
    return {"meta": {"schema": SERIES_SCHEMA, "status": (payload.get("meta") or {}).get("status"),
                     "importedAt": snap.get("importedAt"), "sha256": snap.get("sha256"),
                     "order": "stage of the season, region, week, day, game (the sheet has no dates)"},
            "stageOrder": STAGE_ORDER, "regionOrder": REGION_ORDER,
            "records": records, "series": rows}


# ------------------------------------------------------------------ render
def _compact(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def render_summary(summary: dict) -> str:
    body = dict(summary)
    heroes = body.pop("heroes", {})
    profiles = body.pop("teamProfiles", {})
    head = _compact(body)[:-1]
    h = ",\n".join(f"{json.dumps(k, ensure_ascii=False)}:{_compact(v)}" for k, v in heroes.items())
    t = ",\n".join(f"{json.dumps(k, ensure_ascii=False)}:{_compact(v)}" for k, v in profiles.items())
    return SUMMARY_HEADER + head + ',\n"heroes":{\n' + h + '\n},\n"teamProfiles":{\n' + t + "\n}};\n"


def render_series(series: dict) -> str:
    body = dict(series)
    rows = body.pop("series", [])
    head = _compact(body)[:-1]
    return SERIES_HEADER + head + ',\n"series":[\n' + ",\n".join(_compact(r) for r in rows) + "\n]};\n"
