"""
export.py — the public external dataset and the operator reports.

assets/data/external_sheet.v1.js sets `window.OWCS_EXTERNAL`. It is the
FOURTH dataset the site loads and, like the other three, it is never merged
into another one: published VOD data stays in public_data.v1.js, and a page
that shows both labels every number with where it came from
(`VOD verified` / `spreadsheet imported` / `both sources agree` /
`conflicting sources`).

The payload is a pure function of committed files — the raw cell layer, the
configs, the decisions file, the manifest and the published VOD dataset — so
`sheet_sync.py check` can rebuild it in CI and fail on any drift.
"""
from __future__ import annotations

import hashlib
import json
from . import PARSER_VERSION, SCHEMA
from .aliases import norm

HEADER = """/* =====================================================================
   OWCS Comp Tracker — external_sheet.v1.js  (IMPORTED community spreadsheet)
   GENERATED by pipeline/sheet_sync.py — do not hand-edit.
   Spreadsheet observations: what the sheet's editors documented. Never
   timed, never VOD-verified unless a reconciliation record says both
   sources agree. Contract: docs/EXTERNAL-SHEET.md
   ===================================================================== */
window.OWCS_EXTERNAL = """

PROVENANCE_LABELS = {
    "vod": "VOD verified",
    "sheet": "Spreadsheet imported",
    "both": "Both sources agree",
    "conflict": "Conflicting sources",
}


def _map_digest(mp: dict, bans: list, apps: list, comps: list) -> str:
    core = {k: mp.get(k) for k in ("map", "winner", "pickedBy", "mode", "order",
                                   "scoreA", "scoreB", "date", "teamA", "teamB")}
    core["bans"] = sorted((b.get("side") or "", b.get("hero") or b.get("heroRaw") or "") for b in bans)
    core["apps"] = sorted((a["side"], a["position"], a["listOrder"], a.get("hero") or a.get("heroRaw") or "")
                          for a in apps)
    core["comps"] = sorted((c["side"], c["kind"], tuple(c["heroes"])) for c in comps)
    return hashlib.sha1(json.dumps(core, sort_keys=True).encode()).hexdigest()[:16]


def map_digests(normalized: dict) -> dict[str, str]:
    bans, apps, comps = {}, {}, {}
    for b in normalized.get("bans") or []:
        bans.setdefault(b["mapId"], []).append(b)
    for a in normalized.get("appearances") or []:
        apps.setdefault(a["mapId"], []).append(a)
    for c in normalized.get("compositions") or []:
        comps.setdefault(c["mapId"], []).append(c)
    return {m["id"]: _map_digest(m, bans.get(m["id"], []), apps.get(m["id"], []), comps.get(m["id"], []))
            for m in normalized.get("maps") or []}


def changes(previous: dict | None, current: dict) -> dict:
    old = map_digests(previous or {})
    new = map_digests(current)
    added = sorted(set(new) - set(old))
    removed = sorted(set(old) - set(new))
    changed = sorted(k for k in set(new) & set(old) if new[k] != old[k])
    return {"new": len(added), "changed": len(changed), "removed": len(removed),
            "unchanged": len(set(new) & set(old)) - len(changed),
            "newIds": added[:100], "changedIds": changed[:100], "removedIds": removed[:100],
            "baseline": "first import" if previous is None else "previous normalized import"}


# ----------------------------------------------------------------- payload
def _hero_entry(a: dict, hero_names: dict) -> dict:
    e = {"hero": a.get("hero"), "n": a["listOrder"]}
    raw = a.get("heroRaw")
    if a.get("hero") is None or norm(raw) != norm(hero_names.get(a.get("hero"), a.get("hero"))):
        e["raw"] = raw
    return e


def _compact_map(mp: dict, bans: list, apps: list, comps: list, hero_names: dict) -> dict:
    teams = {}
    for side in ("a", "b"):
        players: dict[int, dict] = {}
        for a in sorted((x for x in apps if x["side"] == side), key=lambda x: (x["position"], x["listOrder"])):
            p = players.setdefault(a["position"], {
                "position": a["position"], "player": a.get("player"),
                "playerRaw": a.get("playerRaw"), "playerMapped": a.get("playerMethod") not in ("slug", None),
                "role": a.get("role"), "heroes": []})
            p["heroes"].append(_hero_entry(a, hero_names))
        teams[side] = {
            "players": list(players.values()),
            "comps": [{"kind": c["kind"], "heroes": c["heroes"], "unresolved": c["unresolved"],
                       "complete": c["complete"]} for c in comps if c["side"] == side],
        }
    out = {k: mp.get(k) for k in (
        "id", "slug", "matchId", "date", "order", "orderMethod", "map", "mapRaw", "mode",
        "modeMethod", "teamA", "teamB", "winner", "winnerSide", "winnerRaw", "winnerMethod",
        "pickedBy", "pickedBySide", "pickedByRaw", "pickNote", "scoreA", "scoreB", "scoreRaw",
        "vodUrl", "notes", "flags", "src", "alsoListedAt")}
    if mp.get("card"):
        out["card"] = mp["card"]
    if mp.get("duplicateConflicts"):
        out["duplicateConflicts"] = mp["duplicateConflicts"]
    out["bans"] = [{"side": b.get("side"), "teamId": b.get("teamId"), "hero": b.get("hero"),
                    "raw": b.get("heroRaw"), "order": b.get("order"), "cell": b["src"].get("cell")}
                   for b in sorted(bans, key=lambda b: (b.get("side") or "z", b.get("order") or 0))]
    out["teams"] = teams
    return out


def detail_bucket(map_id: str) -> str:
    """Which detail shard holds a map: two hex characters of its content
    hash, so 256 small files however large the sheet is. Mirrored by
    P.extDetailBucket in assets/js/app/sources.js."""
    return (map_id[5:7] if map_id.startswith("xmap-") else "00").lower()


def _summary_map(d: dict) -> dict:
    """What every analytic needs about one map, and nothing heavier: the
    per-player listings, cell references and raw text stay in the detail
    shard that map.html loads for that one map."""
    out = {k: d.get(k) for k in ("id", "slug", "matchId", "date", "order", "map", "mode",
                                  "teamA", "teamB", "winner", "winnerSide", "pickedBy",
                                  "pickNote", "scoreRaw", "vodUrl", "flags")}
    if not d.get("map"):
        out["mapRaw"] = d.get("mapRaw")
    if d.get("duplicateConflicts"):
        out["duplicateConflicts"] = len(d["duplicateConflicts"])
    out["bans"] = [{k: v for k, v in (("side", b["side"]), ("teamId", b["teamId"]), ("hero", b["hero"]),
                                       ("raw", None if b["hero"] else b["raw"])) if v is not None}
                   for b in d["bans"]]
    teams = {}
    for side, t in d["teams"].items():
        heroes = sorted({h["hero"] for p in t["players"] for h in p["heroes"] if h.get("hero")} |
                        {h for c in t["comps"] for h in c["heroes"]})
        comp = next((c for c in t["comps"] if c["kind"] == "listed-comp" and c["complete"]), None) or \
            next((c for c in t["comps"] if c["kind"] == "first-listed" and c["complete"]), None)
        teams[side] = {"heroes": heroes,
                       "comp": sorted(comp["heroes"]) if comp else None,
                       "compKind": comp["kind"] if comp else None,
                       "listed": sum(len(p["heroes"]) for p in t["players"]),
                       "unresolved": sum(1 for p in t["players"] for h in p["heroes"] if not h.get("hero"))}
    out["teams"] = teams
    return out


def _team_names(normalized: dict) -> dict:
    """Display names for teams no registry knows (slug ids), from the
    sheet's own spelling — shown with an 'unmapped' marker, never as a
    verified organisation."""
    names = {}
    for m in normalized.get("matches") or []:
        for side in ("A", "B"):
            tid, raw, method = m.get("team" + side), m.get(f"team{side}Raw"), m.get(f"team{side}Method")
            if tid and tid not in names:
                names[tid] = {"id": tid, "name": raw, "mapped": method not in ("slug", None)}
    return dict(sorted(names.items()))


def build_payload(*, normalized: dict | None, recon: dict | None, manifest: dict,
                  source: dict, decisions: dict, hero_names: dict, fixture: bool = False,
                  extra_maps: dict | None = None) -> tuple[dict, dict]:
    """(main payload, {bucket: {map id: detail}})."""
    snapshot = None
    good = None
    if manifest.get("lastGood"):
        good = next((s for s in manifest.get("snapshots") or []
                     if s.get("sha256") == manifest["lastGood"]), None)
    if good:
        snapshot = {k: good.get(k) for k in (
            "sha256", "importedAt", "bytes", "sheetNames", "parserVersion", "layoutVersion",
            "aliasesVersion", "sourceRowCount", "counts", "changes", "sourceUrl")}
    attempt = manifest.get("lastAttempt")
    if normalized is None:
        status = "never-synced" if not attempt else "failed-never-good"
    elif attempt and attempt.get("status") == "failed":
        status = "failed-kept-last-good"
    else:
        status = "ok"

    normalized = normalized or {}
    inv = normalized.get("inventory") or {}
    bans, apps, comps = {}, {}, {}
    for b in normalized.get("bans") or []:
        bans.setdefault(b["mapId"], []).append(b)
    for a in normalized.get("appearances") or []:
        apps.setdefault(a["mapId"], []).append(a)
    for c in normalized.get("compositions") or []:
        comps.setdefault(c["mapId"], []).append(c)
    ignored = {r["externalMapId"] for r in (recon or {}).get("records") or [] if r.get("ignored")}
    detail_maps = [_compact_map(m, bans.get(m["id"], []), apps.get(m["id"], []), comps.get(m["id"], []),
                                hero_names)
                   for m in normalized.get("maps") or [] if m["id"] not in ignored]
    maps = [_summary_map(d) for d in detail_maps]
    details: dict[str, dict] = {}
    for d in detail_maps:
        details.setdefault(detail_bucket(d["id"]), {})[d["id"]] = d
    recon = recon or {"records": [], "summary": {}, "vodOnlyMaps": [], "rules": {}}
    # A record with no candidate, no link and no decision says only
    # "unmatched", which the summary already counts — leave it out.
    records = [r for r in recon.get("records") or []
               if r.get("vodMapId") or r.get("candidates") or r.get("decisions") or r.get("ignored")
               or r.get("status") != "unmatched"]
    tabs = []
    for t in inv.get("tabs") or []:
        tabs.append(dict(t, ignoredRows=t.get("ignoredRows", [])[:10]))
    unmapped = {k: v[:40] for k, v in (inv.get("unmapped") or {}).items()}
    return {
        "meta": {
            "schema": SCHEMA,
            "fixture": bool(fixture),
            "status": status,
            "parserVersion": PARSER_VERSION,
            "provenanceLabels": PROVENANCE_LABELS,
            "note": ("Spreadsheet observations imported from a community-maintained Google "
                     "Sheet. They record what its editors documented — map picks, results, "
                     "bans and the heroes listed for each player — with no timing and no "
                     "evidence frames. Nothing here is VOD-verified unless its reconciliation "
                     "record says both sources agree."),
            "fixtureNote": ("FIXTURE DATA — built from the synthetic test workbook in "
                            "pipeline/fixtures/gsheet/, not from the real spreadsheet."
                            if fixture else None),
        },
        "source": {
            "id": source.get("id"), "label": source.get("label"),
            "spreadsheetId": source.get("spreadsheetId"), "viewUrl": source.get("viewUrl"),
            "exportUrl": source.get("exportUrl"), "maintainer": source.get("maintainer"),
            "creditNote": source.get("creditNote"),
            "creditsFound": inv.get("credits") or [],
        },
        "snapshot": snapshot,
        "lastAttempt": attempt,
        "history": [{k: s.get(k) for k in ("sha256", "importedAt", "status", "counts", "changes")}
                    for s in (manifest.get("snapshots") or [])[-10:]],
        "teams": _team_names(normalized),
        # Maps the sheet uses that the published catalog does not list
        # (config/external/aliases.json extraMaps), so pages can name them.
        "mapsExtra": {mid: v for mid, v in sorted((extra_maps or {}).items())
                      if any(m.get("map") == mid for m in normalized.get("maps") or [])},
        "tournaments": normalized.get("tournaments") or [],
        "matches": [{k: v for k, v in m.items()} for m in normalized.get("matches") or []],
        "maps": maps,
        "detailShards": sorted(details),
        "reconciliation": {
            "summary": recon.get("summary") or {},
            "rules": recon.get("rules") or {},
            "vodOnlyMaps": recon.get("vodOnlyMaps") or [],
            "records": records,
        },
        "decisions": {"decisions": decisions.get("decisions") or [],
                      "aliasApprovals": decisions.get("aliasApprovals") or [],
                      "version": decisions.get("version")},
        "health": {
            "counts": inv.get("counts") or {},
            "tabCount": inv.get("tabCount", 0),
            "dataTabs": inv.get("dataTabs", 0),
            "sourceRowCount": inv.get("sourceRowCount", 0),
            "layoutVersion": inv.get("layoutVersion"),
            "aliasesVersion": inv.get("aliasesVersion"),
            "tabs": tabs,
            "package": inv.get("package"),
            "unmapped": unmapped,
            "issues": (inv.get("issues") or [])[:100],
            "errors": inv.get("errors") or [],
            "matchCards": inv.get("matchCards"),
            "selfCheck": inv.get("selfCheck"),
        },
    }, details


def _compact_json(obj) -> str:
    # One map per line keeps a sync PR's diff readable; no indentation
    # keeps a large sheet's export small.
    return json.dumps(obj, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def render(payload: dict) -> str:
    body = dict(payload)
    maps = body.pop("maps", [])
    head = _compact_json(body)
    lines = ",\n".join(_compact_json(m) for m in maps)
    return HEADER + head[:-1] + ',\n"maps":[\n' + lines + "\n]};\n"


DETAIL_HEADER = """/* OWCS Comp Tracker — external_sheet/detail-{bucket}.js
   GENERATED by pipeline/sheet_sync.py — do not hand-edit. Per-player
   spreadsheet listings for the maps whose id hashes to '{bucket}'; loaded
   by map.html only. Spreadsheet observations: untimed. */
"""


def render_detail(bucket: str, maps: dict) -> str:
    lines = ",\n".join(f"{json.dumps(k)}:{_compact_json(v)}" for k, v in sorted(maps.items()))
    return (DETAIL_HEADER.format(bucket=bucket) +
            "Object.assign((window.OWCS_EXTERNAL_DETAIL = window.OWCS_EXTERNAL_DETAIL || {}), {\n" +
            lines + "\n});\n")


