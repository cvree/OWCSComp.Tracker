def inventory_markdown(inv: dict, snapshot: dict | None, source: dict) -> str:
    c = inv.get("counts") or {}
    lines = [
        "# Source inventory — community spreadsheet",
        "",
        f"- Source: {source.get('viewUrl')}",
        f"- Spreadsheet id: `{source.get('spreadsheetId')}`",
        f"- Snapshot: `{(snapshot or {}).get('sha256', 'n/a')}` imported "
        f"{(snapshot or {}).get('importedAt', 'n/a')}",
        f"- Parser {inv.get('parserVersion')} · layout v{inv.get('layoutVersion')} · "
        f"aliases v{inv.get('aliasesVersion')}",
        f"- Tabs: {inv.get('tabCount', 0)} ({inv.get('dataTabs', 0)} recognised as data) · "
        f"source rows: {inv.get('sourceRowCount', 0)}",
        "",
        f"**Imported:** {c.get('matches', 0)} matches · {c.get('maps', 0)} maps · "
        f"{c.get('bans', 0)} hero bans · {c.get('appearances', 0)} player-hero appearances · "
        f"{c.get('compositions', 0)} composition observations · "
        f"{c.get('ignoredRows', 0)} ignored rows · {c.get('unmappedValues', 0)} unmapped values · "
        f"{c.get('duplicates', 0)} identical duplicates · {c.get('duplicateConflicts', 0)} conflicting duplicates",
        "",
        "| # | tab | rows | purpose | header row | maps | bans | appearances | ignored |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for t in inv.get("tabs") or []:
        p = t.get("parsed") or {}
        lines.append(f"| {t['index'] + 1} | {t['name']} | {t['rows']} | {t['purpose']} | "
                     f"{t.get('headerRow') or '—'} | {p.get('maps', 0)} | {p.get('bans', 0)} | "
                     f"{p.get('appearances', 0)} | {t.get('ignoredCount', 0)} |")
    for t in inv.get("tabs") or []:
        lines += ["", f"## {t['name']} — {t['purposeLabel']}"]
        if t.get("mappedColumns"):
            lines.append("Columns: " + "; ".join(f"{m['column']} “{m['header']}” → {m['as']}"
                                                 for m in t["mappedColumns"]))
        if t.get("unmappedColumns"):
            lines.append("Unmapped columns (kept in the raw layer): " +
                         "; ".join(f"{m['column']} “{m['header']}”" for m in t["unmappedColumns"]))
        for r in t.get("ignoredRows") or []:
            lines.append(f"- ignored row {r['row']}: {r['reason']}")
    if inv.get("unmapped"):
        lines += ["", "## Unmapped values", ""]
        for kind, rows in inv["unmapped"].items():
            lines.append(f"- **{kind}**: " + ", ".join(
                f"“{r['raw']}” ×{r['count']} ({', '.join(r['refs'][:2])})" for r in rows[:25]))
    if inv.get("credits"):
        lines += ["", "## Credit text found in the workbook", ""]
        lines += [f"- {c['sheet']}!{c['cell']}: {c['text']}" for c in inv["credits"]]
    if inv.get("issues"):
        lines += ["", "## Issues", ""]
        lines += [f"- [{i['level']}] {i['code']}: {i['message']}" for i in inv["issues"][:100]]
    if inv.get("errors"):
        lines += ["", "## Errors", ""]
        lines += [f"- {e['code']}{' (accepted)' if e.get('accepted') else ''}: {e['message']}"
                  for e in inv["errors"]]
    return "\n".join(lines) + "\n"


def reconciliation_markdown(recon: dict) -> str:
    s = recon.get("summary") or {}
    lines = ["# Reconciliation — spreadsheet maps vs VOD-verified maps", "",
             " · ".join(f"{k}: {v}" for k, v in s.items()), "",
             "| spreadsheet map | status | VOD map | method | score | reason |",
             "|---|---|---|---|---|---|"]
    for r in recon.get("records") or []:
        if r["status"] == "unmatched" and not r["candidates"] and not r["decisions"]:
            continue
        lines.append(f"| {r['externalMapId']} | {r['status']} | {r['vodMapId'] or '—'} | "
                     f"{r['method'] or '—'} | {r['score'] if r['score'] is not None else '—'} | "
                     f"{r['reason'] or ''} |")
    unmatched = sum(1 for r in recon.get("records") or [] if r["status"] == "unmatched")
    lines += ["", f"{unmatched} spreadsheet maps have no VOD candidate (spreadsheet-only coverage).",
              f"VOD maps with no spreadsheet record: {', '.join(recon.get('vodOnlyMaps') or []) or 'none'}"]
    return "\n".join(lines) + "\n"


def failure_markdown(failure: dict) -> str:
    lines = ["# Spreadsheet sync FAILED — last good import kept", "",
             f"- When: {failure.get('at')}",
             f"- Stage: {failure.get('stage')}",
             f"- Reason: {failure.get('reason')}",
             f"- Last good snapshot: `{failure.get('lastGood') or 'none'}`",
             "", "Nothing under data/external/ or assets/data/external_sheet.v1.js was replaced."]
    inv = failure.get("inventory") or {}
    if inv.get("tabs"):
        lines += ["", "Tabs seen in the failed download:"]
        for t in inv["tabs"]:
            lines.append(f"- {t['name']}: {t['purpose']} (header row {t.get('headerRow') or '—'}; "
                         f"columns: {[c['header'] for c in t.get('mappedColumns', [])][:10]})")
    for e in inv.get("errors") or []:
        lines.append(f"- {e['code']}: {e['message']}")
    return "\n".join(lines) + "\n"


def hero_names_from(public: dict) -> dict:
    return {h["id"]: h.get("name") or h["id"] for h in public.get("heroes") or []}
