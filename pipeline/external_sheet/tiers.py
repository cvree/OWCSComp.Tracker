"""
tiers.py — the compact input of the Tiers page (tiers.html).

    assets/data/sheet_tiers.v1.js   window.OWCS_SHEET_TIERS

One row per spreadsheet series and one per map, holding only what the
tier maths needs:

  * an ESTIMATED calendar date per series, from the sheet's own position
    (region + stage + Week N | Day N) and config/external/sheet_schedule.json.
    The sheet has no dates; these are published with method
    'schedule-estimate' and the page labels them "estimated". They are
    never written back into the imported records.
  * the event key and bracket round (the card's format text), which set a
    map's importance;
  * per side: order-weighted hero shares (a player's 1st-listed hero counts
    more than a later swap, `listWeights` in config/tier_weights.json), the
    first-listed comp when complete, and bans;
  * the map winner side, or none when the sheet has no winner or the VOD
    reading disputes it (same rule as summary.py: a disputed winner is in
    no win count);
  * each team's home region (Elo seed) and name.

config/tier_weights.json is copied in whole so the browser computes power
ratings, win value and tiers for any as-of date and range
(assets/js/app/tierstats.js). Pure function of the payload + details +
the two configs; `sheet_sync.py check` fails on drift like every other
export file.
"""
from __future__ import annotations

import datetime as dt
import json
import os
from collections import Counter, defaultdict

from .summary import _disputed, series_key

TIERS_SCHEMA = "sheet-tiers.v1"

TIERS_HEADER = """/* =====================================================================
   OWCS Comp Tracker — sheet_tiers.v1.js  (IMPORTED community spreadsheet)
   GENERATED by pipeline/sheet_sync.py — do not hand-edit. Compact input
   of tiers.html: series with ESTIMATED dates (the sheet has none; see
   config/external/sheet_schedule.json), bracket rounds, map winners and
   order-weighted hero listings. Spreadsheet observations: untimed.
   Contract: docs/TIERS.md
   ===================================================================== */
window.OWCS_SHEET_TIERS = """

HOME_REGIONS = {"na", "emea", "korea", "japan", "china", "pacific"}


def load_configs(root: str) -> tuple[dict, dict]:
    def rd(*parts):
        try:
            with open(os.path.join(root, *parts), encoding="utf-8") as f:
                return json.load(f)
        except (OSError, ValueError):
            return {}
    return rd("config", "external", "sheet_schedule.json"), rd("config", "tier_weights.json")


def schedule_key(m: dict) -> str:
    stage = m.get("stageKey") or m.get("stage") or ""
    return f"{m.get('region') or stage}/{stage}"


def event_key(m: dict) -> str:
    stage = m.get("stageKey") or m.get("stage") or ""
    if m.get("region") == "asia":
        return f"asia/{stage}"
    return stage


def estimate_date(m: dict, schedule: dict) -> tuple[str | None, str | None]:
    """(ISO date, confidence) for a series, or (None, None)."""
    entry = (schedule.get("stages") or {}).get(schedule_key(m))
    if not entry:
        return None, None
    step = int(schedule.get("dayStep") or 1)
    day = m.get("day") if isinstance(m.get("day"), int) else 1
    conf = entry.get("confidence") or "estimate"
    if entry.get("days"):
        days = entry["days"]
        if str(day) in days:
            return days[str(day)], conf
        last = max(int(k) for k in days)
        base = dt.date.fromisoformat(days[str(last)])
        return (base + dt.timedelta(days=(day - last) * step)).isoformat(), "estimate"
    weeks = entry.get("weeks") or {}
    if not weeks:
        return None, None
    week = m.get("week") if isinstance(m.get("week"), int) else 1
    if str(week) in weeks:
        base = dt.date.fromisoformat(weeks[str(week)])
    else:
        known = sorted(int(k) for k in weeks)
        prior = [k for k in known if k < week] or [known[0]]
        ref = prior[-1]
        base = dt.date.fromisoformat(weeks[str(ref)]) + dt.timedelta(days=7 * (week - ref))
        conf = "estimate"
    return (base + dt.timedelta(days=(day - 1) * step)).isoformat(), conf


def side_shares(players: list, list_weights: dict) -> list:
    """[[hero, share], …] for one side: each player contributes 1.0 split
    over their listed heroes by listing order."""
    acc: dict[str, float] = defaultdict(float)
    for p in players or []:
        hs = sorted((h for h in p.get("heroes") or [] if h.get("hero")), key=lambda h: h.get("n") or 9)
        if not hs:
            continue
        w = list_weights.get(str(min(len(hs), 3))) or [1.0 / len(hs)] * len(hs)
        if len(hs) > 3:   # never more than three in practice; spread the rest evenly
            w = [x * 0.9 for x in w] + [0.1 / (len(hs) - 3)] * (len(hs) - 3)
        for h, x in zip(hs, w):
            acc[h["hero"]] += x
    return [[h, round(v, 3)] for h, v in sorted(acc.items(), key=lambda kv: (-kv[1], kv[0]))]


def first_comp(team_detail: dict) -> list | None:
    for c in team_detail.get("comps") or []:
        if c.get("kind") == "first-listed" and c.get("complete"):
            return list(c.get("heroes") or [])
    return None


def build_tiers(payload: dict, details: dict, schedule: dict, weights: dict) -> dict:
    detail = {}
    for maps in (details or {}).values():
        detail.update(maps)
    recs = {r["externalMapId"]: r for r in ((payload.get("reconciliation") or {}).get("records") or [])}
    team_names = payload.get("teams") or {}
    list_weights = weights.get("listWeights") or {}

    matches = sorted(payload.get("matches") or [], key=series_key)
    idx = {}
    m_rows = []
    home = defaultdict(Counter)
    conf_count = Counter()
    for m in matches:
        date, conf = estimate_date(m, schedule)
        conf_count[conf or "none"] += 1
        idx[m["id"]] = len(m_rows)
        m_rows.append({"id": m["id"], "d": date, "dc": conf, "r": m.get("region"),
                       "s": m.get("stageKey") or m.get("stage"), "ev": event_key(m),
                       "f": (m.get("format") or "").split(" [")[0] or None, "bo": m.get("bestOf"),
                       "a": m.get("teamA"), "b": m.get("teamB"), "lbl": m.get("gameLabel"),
                       "sl": m.get("slug")})
        if m.get("region") in HOME_REGIONS:
            for t in (m.get("teamA"), m.get("teamB")):
                if t:
                    home[t][m["region"]] += 1

    map_rows = []
    disputed = 0
    for mp in payload.get("maps") or []:
        if mp.get("matchId") not in idx:
            continue
        d = detail.get(mp["id"]) or {}
        dt_ = d.get("teams") or {}
        w = mp.get("winnerSide") if mp.get("winnerSide") in ("a", "b") else None
        if w and _disputed(recs.get(mp["id"])):
            w = None
            disputed += 1
        row = {"m": idx[mp["matchId"]], "id": mp["id"], "map": mp.get("map"), "mode": mp.get("mode"),
               "o": mp.get("order"), "w": w}
        for side in ("a", "b"):
            td = dt_.get(side) or {}
            row[side] = {"h": side_shares(td.get("players"), list_weights),
                         "c": first_comp(td),
                         "bn": sorted({b["hero"] for b in mp.get("bans") or []
                                       if b.get("side") == side and b.get("hero")})}
        map_rows.append(row)
    map_rows.sort(key=lambda r: (r["m"], r["o"] or 0, r["id"]))

    teams = {}
    for t in sorted({x for r in m_rows for x in (r["a"], r["b"]) if x}):
        reg = home[t].most_common(1)[0][0] if home[t] else None
        name = (team_names.get(t) or {}).get("name") if isinstance(team_names.get(t), dict) else None
        teams[t] = [name or t, reg]

    stages_meta = {k: {"confidence": v.get("confidence"), "source": v.get("source"), "label": v.get("label")}
                   for k, v in sorted((schedule.get("stages") or {}).items())}
    dates = [r["d"] for r in m_rows if r["d"]]
    return {
        "schema": TIERS_SCHEMA,
        "snapshot": ((payload.get("snapshot") or {}).get("sha256") or None),
        "dates": {"method": "schedule-estimate", "min": min(dates) if dates else None,
                  "max": max(dates) if dates else None, "confidence": dict(sorted(conf_count.items())),
                  "stages": stages_meta},
        "counts": {"series": len(m_rows), "maps": len(map_rows), "disputedWinners": disputed},
        "weights": {k: v for k, v in weights.items() if not k.startswith("_")},
        "teams": teams,
        "matches": m_rows,
        "maps": map_rows,
    }


def _compact(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def render_tiers(doc: dict) -> str:
    body = dict(doc)
    matches = body.pop("matches", [])
    maps = body.pop("maps", [])
    head = _compact(body)[:-1]
    return (TIERS_HEADER + head + ',\n"matches":[\n' + ",\n".join(_compact(r) for r in matches) +
            '\n],\n"maps":[\n' + ",\n".join(_compact(r) for r in maps) + "\n]};\n")
