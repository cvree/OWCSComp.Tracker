# purpose: the config is the source of truth, it is offline, and the public
# build must not require the operator's private job database.
CALENDAR_CONFIG = os.path.join(db.REPO_ROOT, "config", "owcs_calendar.json")


def build_calendar_events(path: str = CALENDAR_CONFIG) -> list[dict]:
    """Official-calendar events for the public dataset.

    `verified` is carried through UNCHANGED. Every event in the committed
    seed is currently `verified: false` (the official schedule site was not
    reachable when it was written), and the site is required to say so
    rather than present placeholder dates as fact.
    """
    if not os.path.exists(path):
        return []
    try:
        with open(path, "r", encoding="utf-8") as f:
            raw = json.load(f)
    except (OSError, ValueError):
        return []
    out = []
    for e in raw.get("events", []) or []:
        eid = e.get("id")
        if not eid or not e.get("startDate"):
            continue        # an event with no id or no start cannot be placed
        out.append({
            "id": eid,
            "name": e.get("name") or eid,
            "region": (e.get("region") or "global").lower(),
            "stage": e.get("stage"),
            "startDate": e.get("startDate"),
            "endDate": e.get("endDate") or e.get("startDate"),
            "verified": bool(e.get("verified")),
            "broadcastChannels": list(e.get("broadcastChannels") or []),
            "faceitCompetitionId": e.get("faceitCompetitionId"),
        })
    out.sort(key=lambda e: (e["startDate"], e["id"]))
    return out


def build_public_payload(con) -> dict:
    """The production public.v1 dataset, built ONLY from reviewed/staged
    DB state: matches, map_results, hero_stints (approved statuses),
    hero_swaps, ingest_runs. Nothing is invented; missing facts stay null
    with honest notes."""
    now = dt.datetime.now(dt.timezone.utc).isoformat()
    heroes = attach_portraits(
        [{"id": r["id"], "name": r["name"], "role": r["role"]}
         for r in con.execute("SELECT * FROM heroes ORDER BY role, name")])
    maps_catalog = [{"id": r["id"], "name": r["name"], "mode": r["mode"]}
                    for r in con.execute(
                        "SELECT * FROM game_maps ORDER BY name")]

    roster_size = con.execute("SELECT COUNT(*) FROM heroes").fetchone()[0]
    ingest_rows = con.execute(
        "SELECT * FROM ingest_runs WHERE status='complete'").fetchall()
    match_ids = sorted({r["match_id"] for r in ingest_rows
                        if r["match_id"]})
    hero_bans_out: list[dict] = []

    teams_needed: set[str] = set()
    matches_out, runs_out, snaps_out, players_out = [], [], [], []
    swaps_out: list[dict] = []
    # Phase 7 contract: the hero-stint timeline itself, not only the comp
    # snapshots derived from it. Only APPROVED stints are emitted — the same
    # 'auto-high'/'reviewed' gate every other public number uses.
    hero_stints_out: list[dict] = []
    vod_out: dict[str, dict] = {}
    tournaments_by_id: dict[str, dict] = {}

    for mid in match_ids:
        m = con.execute("SELECT * FROM matches WHERE id=?",
                        (mid,)).fetchone()
        if m is None:
            continue
        teams_needed.update((m["team_a"], m["team_b"]))
        tid = _tournament_id(m)
        maps_out = []
        for mr in con.execute(
                """SELECT * FROM map_results WHERE match_id=?
                   ORDER BY map_order""", (mid,)).fetchall():
            rounds = con.execute(
                """SELECT * FROM map_rounds WHERE map_result_id=?
                   ORDER BY round_index""", (mr["id"],)).fetchall()
            stints = _stints_for_map(con, mr["id"])
            map_pub_id_for_stints = f"{mid}-m{mr['map_order']}"
            for st in stints:
                if rv(st, "status") not in APPROVED_REVIEW_STATES:
                    continue
                evs, eve = rv(st, "evidence_start"), rv(st, "evidence_end")
                hero_stints_out.append({
                    "id": (f"hs-{map_pub_id_for_stints}-{st['team_id']}-"
                           f"{st['slot']}-{st['start_offset']}"),
                    "matchId": mid, "mapId": map_pub_id_for_stints,
                    "teamId": st["team_id"], "side": rv(st, "side"),
                    "slot": rv(st, "slot"), "hero": st["hero_id"],
                    "start": rv(st, "start_offset"), "end": rv(st, "end_offset"),
                    "observations": rv(st, "n_obs"),
                    "meanConfidence": rv(st, "mean_conf"),
                    "minConfidence": rv(st, "min_conf"),
                    "reviewStatus": rv(st, "status"),
                    "source": ("manual" if rv(st, "manual_override") else
                               rv(st, "source", "cv")),
                    "detectorVersion": rv(st, "detector_version"),
                    "evidenceStart": evs if evs and os.path.exists(
                        os.path.join(db.REPO_ROOT, evs)) else None,
                    "evidenceEnd": eve if eve and os.path.exists(
                        os.path.join(db.REPO_ROOT, eve)) else None,
                    "ingestId": rv(st, "ingest_id"),
                })
            run = next((r for r in ingest_rows
                        if r["match_id"] == mid
                        and r["map_order"] == mr["map_order"]), None)
            map_pub_id = f"{mid}-m{mr['map_order']}"
            mode = next((c["mode"] for c in maps_catalog
                         if c["id"] == mr["map_id"]), None)
            maps_out.append({
                "id": map_pub_id,
                "order": mr["map_order"],
                "map": mr["map_id"],
                "mode": mode,
                "winner": rv(mr, "winner_team"),
                "scoreA": rv(mr, "score_a"),
                "scoreB": rv(mr, "score_b"),
                # per-round capture % is not measured by the CV pipeline
                # yet -> null means the page renders its honest fallback.
                # roundCount IS real (segmented by the round-emblem detector)
                # — the honest first step toward per-submap detail.
                "scoreDetail": None,
                "roundCount": len(rounds),
                # real round windows from the round-emblem detector —
                # broadcast offsets in seconds, ±1 sample (~5 s).
                "rounds": [{"index": r_["round_index"],
                            "start": rv(r_, "start_offset"),
                            "end": rv(r_, "end_offset"),
                            "confidence": rv(r_, "confidence"),
                            "source": rv(r_, "source", "cv")}
                           for r_ in rounds],
                "pickedBy": rv(mr, "picked_by_team"),
                "pickNote": None,
            })
            # hero swaps for this map — the temporal-consensus verdicts,
            # confirmed AND rejected. Confirmed rows carry before/after
            # evidence crops; rejected rows carry the honest reason they
            # were thrown out. Nothing here is invented.
            for s in con.execute(
                    """SELECT * FROM hero_swaps WHERE map_result_id=?
                       ORDER BY offset_seconds""", (mr["id"],)):
                evb, eva = rv(s, "evidence_before"), rv(s, "evidence_after")
                swaps_out.append({
                    "id": f"sw-{map_pub_id}-{s['team_id']}-{s['slot']}-"
                          f"{s['offset_seconds']}-{s['status']}",
                    "matchId": mid,
                    "mapId": map_pub_id,
                    "teamId": s["team_id"],
                    "side": rv(s, "side"),
                    "slot": rv(s, "slot"),
                    "fromHero": s["from_hero"],
                    "toHero": s["to_hero"],
                    "offset": rv(s, "offset_seconds"),
                    "confidence": rv(s, "confidence"),
                    "status": s["status"],
                    "reason": rv(s, "reason"),
                    "evidenceBefore": evb if evb and os.path.exists(
                        os.path.join(db.REPO_ROOT, evb)) else None,
                    "evidenceAfter": eva if eva and os.path.exists(
                        os.path.join(db.REPO_ROOT, eva)) else None,
                    "ingestId": rv(s, "ingest_id"),
                })
            # hero bans for this map (real match facts; empty when the
            # broadcast/import recorded none — the UI says so honestly).
            for b in con.execute(
                    """SELECT * FROM hero_bans WHERE match_id=?
                       AND (map_result_id=? OR map_result_id IS NULL)
                       ORDER BY COALESCE(ban_order, id)""",
                    (mid, mr["id"])):
                hero_bans_out.append({
                    "id": f"ban-{map_pub_id}-{b['hero_id']}-{rv(b, 'team_id') or 'x'}",
                    "matchId": mid,
                    "mapId": map_pub_id,
                    "hero": b["hero_id"],
                    "teamId": rv(b, "team_id"),
                    "source": rv(b, "source", "manual"),
                })
            if run is None:
                continue
            frames_rel = f"reports/ingest/{run['id']}/frames"
            approved = {"auto-high", "reviewed"}
            for team in (m["team_a"], m["team_b"]):
                for t in _snapshot_times(con, mr["id"], team, rounds):
                    heroes5, rows = _comp_at(stints, team, t)
                    if len(heroes5) != 5:
                        continue
                    statuses = {r_["status"] for r_ in rows}
                    review = ("auto-high" if statuses <= approved
                              else "needs-review")
                    manual = any(rv(r_, "manual_override") for r_ in rows)
                    confs = [rv(r_, "mean_conf") for r_ in rows
                             if rv(r_, "mean_conf") is not None]
                    side = rows[0]["side"] if rows else None
                    snaps_out.append({
                        "id": f"cs-{map_pub_id}-{team}-{t}",
                        "matchId": mid,
                        "mapId": map_pub_id,
                        "teamId": team,
                        "side": side,
                        "timestamp": t,
                        "heroes": heroes5,
                        "source": "manual" if manual else "cv",
                        "confidence": (round(sum(confs) / len(confs), 3)
                                       if confs else None),
                        "reviewStatus": review,
                        "evidenceRunId": run["id"],
                        "evidenceFrame": _nearest_frame(frames_rel, t),
                    })

        run_ids = [r["id"] for r in ingest_rows if r["match_id"] == mid]
        for r in ingest_rows:
            if r["match_id"] != mid:
                continue
            frames_rel = f"reports/ingest/{r['id']}/frames"
            frames = []
            fdir = os.path.join(db.REPO_ROOT, frames_rel)
            if os.path.isdir(fdir):
                for fn in sorted(os.listdir(fdir)):
                    if fn.startswith("frame_"):
                        try:
                            off = int(fn.split("_")[1].split(".")[0])
                        except ValueError:
                            continue
                        frames.append({"offset": off,
                                       "file": f"{frames_rel}/{fn}",
                                       "layoutDebug": None})
            crops = []
            for s in con.execute(
                    """SELECT evidence_before, evidence_after
                       FROM hero_swaps WHERE ingest_id=?
                       AND status='confirmed'""", (r["id"],)):
                for c in (s["evidence_before"], s["evidence_after"]):
                    if c and os.path.exists(os.path.join(db.REPO_ROOT, c)):
                        crops.append(c)
            runs_out.append({
                "id": r["id"],
                "matchId": mid,
                "sourceId": rv(r, "source_id"),
                "window": {"start": _fmt_clock(rv(r, "start_offset")),
                           "end": _fmt_clock(rv(r, "end_offset")),
                           "every": 5},
                "requestedHeight": 720,
                "actualWidth": 1280,
                "actualHeight": 720,
                "clipMode": "direct-url-cut",
                "status": "needs-review",
                "reportPath": rv(r, "report_path"),
                "createdAt": rv(r, "created_at"),
                "frames": frames,
                "crops": crops,
                "note": ("full-map CV ingestion "
                         f"({rv(r, 'detector_version')}, calibration "
                         f"{rv(r, 'calibration_version')})"),
                # autocalibration provenance for the 'trust this footage'
                # story — real numbers from the source's layout, or null.
                "calibration": calibration_summary(
                    rv(r, "source_id"), roster_size),
                "calibrationStatus": rv(r, "calibration_status", "ok"),
                "calibrationVersion": rv(r, "calibration_version"),
            })

        for p in con.execute(
                """SELECT r.team_id, p.* FROM match_rosters r
                   JOIN players p ON p.id=r.player_id
                   WHERE r.match_id=? AND COALESCE(p.source,'') <> ?""",
                (mid, SAMPLE_PLAYER_SOURCE)):
            players_out.append({"id": p["id"], "teamId": p["team_id"],
                                "handle": p["nickname"],
                                "role": rv(p, "role")})

        vurl = rv(m, "vod_url")
        if vurl:
            vod_out[vurl] = {
                "id": rv(m, "source_ref") or f"vod-{mid}",
                "provider": "youtube",
                "url": vurl,
                "title": rv(m, "event_name") or "OWCS broadcast VOD",
                "matchIds": [mid],
                "heightAvailable": 1080,
            }

        stage_name = rv(m, "stage") or "Matches"
        matches_out.append({
            "id": mid,
            "tournamentId": tid,
            "stageId": f"{tid}-stage",
            "roundId": None,
            "teamA": m["team_a"],
            "teamB": m["team_b"],
            "bestOf": 5,
            # `scheduled_at` is a real start instant; `date` is a day with no
            # time. Deriving midnight from a date and publishing it as
            # `scheduledAt` is fine for placing the match on a calendar, but
            # the UI must not render 00:00 UTC as if it were a kickoff time —
            # hence the explicit flag rather than a magic-value convention.
            "scheduledAt": (rv(m, "scheduled_at")
                            or f"{m['date']}T00:00:00+00:00"),
            "timeKnown": bool(rv(m, "scheduled_at")),
            "status": "completed",
            "scoreA": rv(m, "score_a") or None,
            "scoreB": rv(m, "score_b") or None,
            "winner": rv(m, "winner_team"),
            "streamUrl": vurl,
            "faceitUrl": rv(m, "faceit_room_url"),
            "liquipediaUrl": None,
            "casters": [],
            "sources": [{"type": "vod", "url": vurl,
                         "lastSynced": now}] if vurl else [],
            "captureStatus": "needs-review",
            "captureRunId": run_ids[0] if run_ids else None,
            "summary": (f"{len(maps_out)} map(s) captured and ingested by "
                        "the CV pipeline; series score not yet recorded — "
                        "only verified data is shown."),
            "maps": maps_out,
        })

        if tid not in tournaments_by_id:
            tournaments_by_id[tid] = {
                "id": tid,
                "name": rv(m, "event_name") or "OWCS 2026",
                "series": "OWCS",
                "region": _region_id(rv(m, "region")),
                "tier": "S",
                "year": 2026,
                "startsAt": f"{m['date']}T00:00:00+00:00",
                "endsAt": None,
                "status": "completed",
                "prizePool": None,
                "teamIds": set(),
                "winnerTeamId": None,
                "summary": (f"{stage_name}. Matches appear here as their "
                            "VODs are captured and reviewed."),
                "logoUrl": None,
                "sources": [],
                "stages": [{"id": f"{tid}-stage", "name": stage_name,
                            "order": 1, "format": "Double elimination",
                            "status": "completed"}],
                "standings": [],
            }
        tourn = tournaments_by_id[tid]
        tourn["teamIds"].update((m["team_a"], m["team_b"]))
        if vurl and not any(s["url"] == vurl for s in tourn["sources"]):
            tourn["sources"].append({"type": "vod", "url": vurl,
                                     "lastSynced": now})

    # ---- Phase B: discovered scheduled matches (facts before CV) ----------
    # A match can publish its calendar facts before its compositions are
    # processed (roadmap I3). Any content-DB match in the rolling discovery
    # window that hasn't already been emitted from a CV run is added here with
    # its real scheduled time and an honest capture state, so calendar.html
    # populates the moment FACEIT discovery upserts a match — no comps invented.
    emitted_ids = {mo["id"] for mo in matches_out}
    # Tournaments invented as stubs below start life as "upcoming" because a
    # freshly discovered match carries no event lifecycle of its own. That
    # guess has to be reconciled against the matches once they are all known
    # (see the _reconcile_stub_tournament_status pass after this loop) —
    # otherwise a finished event keeps advertising itself as upcoming.
    stub_tids: set = set()
    for m in _discovered_window_matches(con):
        if m["id"] in emitted_ids:
            continue
        tid = _tournament_id(m)
        vurl = rv(m, "vod_url")
        has_maps = con.execute(
            "SELECT 1 FROM map_results WHERE match_id=? LIMIT 1", (m["id"],)
        ).fetchone() is not None
        teams_needed.update((m["team_a"], m["team_b"]))
        matches_out.append({
            "id": m["id"],
            "tournamentId": tid,
            "stageId": f"{tid}-stage",
            "roundId": None,
            "teamA": m["team_a"],
            "teamB": m["team_b"],
            "bestOf": 5,
            "scheduledAt": (rv(m, "scheduled_at")
                            or f"{m['date']}T00:00:00+00:00"),
            # See the note on the other match builder: midnight derived from
            # a bare date must never render as a real kickoff time.
            "timeKnown": bool(rv(m, "scheduled_at")),
            "status": _public_match_status(m),
            "scoreA": rv(m, "score_a") or None,
            "scoreB": rv(m, "score_b") or None,
            "winner": rv(m, "winner_team"),
            "streamUrl": vurl,
            "faceitUrl": rv(m, "faceit_room_url"),
            "liquipediaUrl": None,
            "casters": [],
            "sources": ([{"type": "vod", "url": vurl, "lastSynced": now}]
                        if vurl else []),
            "captureStatus": _public_capture_status(m, bool(vurl), has_maps),
            "captureRunId": None,
            "summary": ("Discovered from FACEIT; calendar facts only — "
                        "compositions are not yet processed."),
            "maps": [],
        })
        if tid not in tournaments_by_id:
            stub_tids.add(tid)
            stage_name = rv(m, "stage") or "Matches"
            tournaments_by_id[tid] = {
                "id": tid, "name": rv(m, "event_name") or "OWCS 2026",
                "series": "OWCS", "region": _region_id(rv(m, "region")),
                "tier": "S", "year": 2026,
                "startsAt": f"{m['date']}T00:00:00+00:00", "endsAt": None,
                "status": "upcoming", "prizePool": None,
                "teamIds": set(), "winnerTeamId": None,
                "summary": f"{stage_name}. Discovered via FACEIT sync.",
                "logoUrl": None, "sources": [],
                "stages": [{"id": f"{tid}-stage", "name": stage_name,
                            "order": 1, "format": "Double elimination",
                            "status": "upcoming"}],
                "standings": [],
            }
        tournaments_by_id[tid]["teamIds"].update((m["team_a"], m["team_b"]))

    _reconcile_stub_tournament_status(tournaments_by_id, stub_tids, matches_out)

    tournaments_out = [dict(t, teamIds=sorted(t["teamIds"]))
                       for t in tournaments_by_id.values()]

    # Phase D2: every team in the canonical registry is a public entity,
    # independent of whether the vision pipeline has captured any of its
    # maps yet (teams_needed above still scopes tournament rosters/logos
    # elsewhere; it never gates WHICH teams the site knows about).
    asset_sources = _team_asset_sources()
    # hero_stints is the REAL, current full-map CV pipeline's output (the
    # Nepal milestone lives here); comp_snapshots is an older, separate
    # capture path still written by other tools but not what the public
    # compSnapshots payload above is actually built from — using it here
    # would call a team's tracking "pending" or "done" on the wrong signal.
    captured_team_ids = {r["team_id"] for r in con.execute(
        "SELECT DISTINCT team_id FROM hero_stints")} if _has_table(con, "hero_stints") else set()
    teams = [{"id": r["id"], "name": r["name"], "code": r["code"],
              "region": _region_id(rv(r, "region")),
              "logoUrl": rv(r, "logo_url"),
              # Team profile enrichment (Phase D) — FACEIT facts only, never
              # a logo (logoUrl above stays the human-verified asset alone).
              "description": rv(r, "description"),
              "website": rv(r, "website"),
              "socials": {k: v for k, v in
                          {"twitter": rv(r, "twitter"), "facebook": rv(r, "facebook")}.items()
                          if v} or None,
              "memberCount": rv(r, "member_count"),
              # Canonical team registry (Phase D2) — identity/roster facts
              # and explicit coverage states; never a substitute for actual
              # capture evidence (compositionTrackingPending says so plainly).
              "status": rv(r, "status", "active"),
              "organization": rv(r, "organization"),
              "aliases": _json_list(rv(r, "aliases")),
              "previousNames": _json_list(rv(r, "previous_names")),
              "sourceAuthority": rv(r, "source_authority"),
              "identityVerifiedAt": rv(r, "identity_verified_at"),
              "rosterSource": rv(r, "roster_source"),
              "rosterVerifiedAt": rv(r, "roster_verified_at"),
              "roster": _current_roster(con, r["id"]),
              "needsReview": bool(rv(r, "needs_review")),
              "reviewReason": rv(r, "review_reason"),
              "hasLogoCandidate": _has_logo_candidate(r["id"], asset_sources),
              "compositionTrackingPending": r["id"] not in captured_team_ids}
             for r in con.execute("SELECT * FROM teams ORDER BY name")]

    # ---- provisional blocking (Phase 7) ---------------------------------
    # A match carrying unreviewed CV output must not reach the public site.
    # Its calendar facts (teams, schedule, status) are safe and stay; its
    # MAPS and every composition/swap/ban derived from them are withheld,
    # with the reason recorded in meta so the withholding is visible rather
    # than looking like missing data.
    blocked: list[dict] = []
    for mo in matches_out:
        reasons = provisional_reasons(con, mo["id"])
        if not reasons:
            continue
        blocked.append({"matchId": mo["id"], "reasons": reasons})
        mo["maps"] = []
        mo["captureStatus"] = "needs-review"
        mo["summary"] = ("Withheld from publication: "
                         + "; ".join(reasons)
                         + ". Calendar facts only — no composition, swap or "
                           "score from this match is published until review "
                           "is complete.")
    blocked_ids = {b["matchId"] for b in blocked}
    if blocked_ids:
        snaps_out = [s for s in snaps_out if s["matchId"] not in blocked_ids]
        swaps_out = [s for s in swaps_out if s["matchId"] not in blocked_ids]
        hero_bans_out = [b for b in hero_bans_out
                         if b["matchId"] not in blocked_ids]
        runs_out = [r for r in runs_out if r["matchId"] not in blocked_ids]
        hero_stints_out = [s_ for s_ in hero_stints_out
                           if s_["matchId"] not in blocked_ids]

    # ---- derived aggregates (Phase 7) -----------------------------------
    # Computed AFTER provisional blocking, from exactly the rows that will
    # actually ship, so no aggregate can ever include a withheld match.
    comp_frequency, comp_win_rate = build_comp_stats(snaps_out, matches_out)
    hero_rates = build_hero_rates(snaps_out, swaps_out, matches_out)
    team_pools = build_team_hero_pools(snaps_out, matches_out)
    team_map_records = build_team_map_records(matches_out)
    map_stats, mode_stats = build_map_mode_stats(matches_out, maps_catalog)

    return {
        "meta": {
            "schema": "public.v1",
            "demo": False,
            "generatedAt": now,
            "note": ("Production export from data/owcs.sqlite — only "
                     "captured, staged and reviewed data; no invented "
                     "values."),
            # Publication provenance: what was withheld and why, so a gap on
            # the site is always explainable from the export itself.
            "withheldMatches": blocked,
            "withheldCount": len(blocked),
            "approvedReviewStates": list(APPROVED_REVIEW_STATES),
            "aggregatesNote": ("compFrequency/compWinRate/heroPickRates/"
                               "teamHeroPools/teamMapRecords/mapStats/"
                               "modeStats are derived from the approved comp "
                               "snapshots in THIS file, after provisional "
                               "matches were withheld — they can never "
                               "include a withheld match."),
        },
        "regions": REGIONS,
        "teams": teams,
        "players": players_out,
        "tournaments": tournaments_out,
        # The official season structure — stage windows and their broadcast
        # destinations. Carries `verified` unchanged so the calendar can be
        # explicit about which dates are confirmed and which are a seed.
        "calendarEvents": build_calendar_events(),
        "bracketRounds": [],
        "extraRounds": [],
        "bracketMatches": [],
        "matches": matches_out,
        "mapResults": [dict(g, matchId=mo["id"])
                       for mo in matches_out for g in (mo.get("maps") or [])],
        "heroBans": hero_bans_out,
        "heroSwaps": swaps_out,
        "rejectedSwaps": [s for s in swaps_out if s.get("status") != "confirmed"],
        "heroStints": hero_stints_out,
        "captureRuns": runs_out,
        "compSnapshots": snaps_out,
        "vodSources": list(vod_out.values()),
        "heroes": heroes,
        "mapsCatalog": maps_catalog,
        "patches": [],
        # ---- derived aggregates -----------------------------------------
        "compFrequency": comp_frequency,
        "compWinRate": comp_win_rate,
        "heroPickRates": hero_rates,
        "teamHeroPools": team_pools,
        "teamMapRecords": team_map_records,
        "mapStats": map_stats,
        "modeStats": mode_stats,
    }


def _stamp() -> str:
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M")


def render_main_body(payload: dict, ts: str | None = None) -> str:
    """The exact bytes of assets/js/data.js for `payload`.

    Single source of truth so every writer (this module and
    pipeline/run_batch.py) emits a byte-identical file. run_batch used to
    inline its own `json.dumps(payload, indent=1)` WITHOUT
    `ensure_ascii=False`, so a batch run rewrote every non-ASCII team and
    player name as a `\\uXXXX` escape — a whole-file diff against the
    export this module produces, for identical data.
    """
    return (HEADER.format(ts=ts or _stamp())
            + json.dumps(payload, indent=1, ensure_ascii=False) + ";\n")


def render_public_body(payload: dict, ts: str | None = None) -> str:
    """The exact bytes of assets/data/public_data.v1.js for `payload`."""
    return (PUBLIC_HEADER.format(ts=ts or _stamp())
            + json.dumps(payload, indent=1, ensure_ascii=False) + ";\n")


def write_body(path: str, body: str) -> None:
    """Write a generated export deterministically on every platform.

    `newline=""` disables Python's universal-newline translation: without
    it a Windows run turns every "\\n" in `body` into "\\r\\n", so the file
    an operator generates on Windows is byte-different from the one CI
    generates on Linux even when the data is identical.
    """
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(body)


# The generation timestamp is the ONE thing that legitimately differs
# between two exports of the same database: it appears in the banner
# comment, in meta.generatedAt, and (as the same ISO string) in every
# source's `lastSynced`. Nothing else may differ.
_HEADER_TS_RE = re.compile(
    r"(GENERATED by pipeline/export_data\.py[^\n]*? on )"
    r"\d{4}-\d{2}-\d{2} \d{2}:\d{2}( UTC)")
_GENERATED_AT_RE = re.compile(r'"generatedAt":\s*"([^"]+)"')
_TS_PLACEHOLDER = "<GENERATED-AT>"


def normalize_generated(body: str) -> str:
    """Blank out only the generation timestamp, so two exports of the same
    DB compare equal. CRLF is folded to LF first so a Windows checkout
    (or a `core.autocrlf` clone) does not read as drift."""
    body = body.replace("\r\n", "\n")
    body = _HEADER_TS_RE.sub(r"\g<1>" + _TS_PLACEHOLDER + r"\g<2>", body)
    m = _GENERATED_AT_RE.search(body)
    if m and m.group(1):
        body = body.replace(m.group(1), _TS_PLACEHOLDER)
    return body


def check_reproducible(con, public: bool = False) -> int:
    """Fail loudly when a committed export no longer matches the database.

    This is the gate ci.yml runs. It deliberately does NOT write anything:
    regenerating in place left the working tree dirty, which made
    test_release_reproducibility's "the suite leaves the tree clean" guard
    skip itself on every CI run.
    """
    targets: list[tuple[str, str]] = [
        (OUT_PATH, render_main_body(build_payload(con)))]
    if public:
        targets.append(
            (PUBLIC_OUT_PATH, render_public_body(build_public_payload(con))))

    problems: list[str] = []
    for path, fresh in targets:
        rel = os.path.relpath(path, db.REPO_ROOT).replace(os.sep, "/")
        if not os.path.exists(path):
            problems.append(f"{rel}: MISSING — nothing to compare against; "
                            f"run the exporter and commit the result")
            continue
        with open(path, encoding="utf-8", newline="") as f:
            committed = f.read()
        a = normalize_generated(committed)
        b = normalize_generated(fresh)
        if a == b:
            print(f"REPRODUCIBLE  {rel} (matches a fresh export from "
                  f"data/owcs.sqlite; timestamp aside)")
            continue
        diff = difflib.unified_diff(
            a.splitlines(), b.splitlines(),
            fromfile=f"{rel} (committed)", tofile=f"{rel} (fresh export)",
            lineterm="", n=2)
        excerpt = "\n".join(itertools.islice(diff, 120))
        problems.append(
            f"{rel}: DRIFT — the committed file is not what "
            f"pipeline/export_data.py produces from data/owcs.sqlite today. "
            f"Re-export and commit the result.\n{excerpt}")

    if problems:
        print("\nEXPORT REPRODUCIBILITY CHECK FAILED:", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        return 1
    return 0


def write_public(con) -> str:
    payload = build_public_payload(con)
    write_body(PUBLIC_OUT_PATH, render_public_body(payload))
    print(f"Wrote {PUBLIC_OUT_PATH}: {len(payload['matches'])} matches, "
          f"{len(payload['compSnapshots'])} comp snapshots, "
          f"{len(payload['captureRuns'])} capture runs.")
    return PUBLIC_OUT_PATH


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stdout", action="store_true",
                    help="print JSON instead of writing data.js")
    ap.add_argument("--public", action="store_true",
                    help="ALSO write assets/data/public_data.v1.js "
                         "(production public dataset)")
    ap.add_argument("--check", action="store_true",
                    help="write NOTHING; verify the committed export(s) "
                         "still match a fresh export from data/owcs.sqlite "
                         "(generation timestamp aside). Exit 1 on drift. "
                         "Combine with --public to check both files.")
    args = ap.parse_args()

    con = db.connect()

    if args.check:
        return check_reproducible(con, public=args.public)

    payload = build_payload(con)

    if args.stdout:
        json.dump(payload, sys.stdout, indent=1)
        return 0

    write_body(OUT_PATH, render_main_body(payload))
    bans = sum(len(g["faceit"]["heroBans"]) for m_ in payload["matches"] for g in m_["maps"])
    detected = sum(1 for m_ in payload["matches"] for g in m_["maps"] if g["tracker"]["detected"])
    total = sum(len(m_["maps"]) for m_ in payload["matches"])
    print(f"Wrote {OUT_PATH}: {len(payload['matches'])} matches, "
          f"{total} maps ({detected} with tracker comps, "
          f"{total - detected} FACEIT-only), {bans} hero bans.")
    if args.public:
        write_public(con)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
