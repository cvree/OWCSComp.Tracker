def _fixture_kind(m: Any) -> str:
    """'production' or 'synthetic' for a matches row (see
    automation/match_repair.py — evidence is the row's own source_ref/
    faceit_match_id, never a guess). Falls back to 'production' (never
    hides a match) if the automation package isn't importable yet."""
    try:
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        from automation import match_repair as _mrepair  # noqa: WPS433
        return _mrepair.classify_fixture_kind(m)
    except Exception:
        return "production"


def _discovered_window_matches(con) -> list[Any]:
    """Content-DB matches the exporter should surface outside the CV-ingest
    path, ordered for a stable export.

    Two evidence-based eligibility routes (Phase D2.1):
      * FACEIT/calendar-discovered (competition_id or lifecycle_status set)
        — kept only inside the rolling discovery window, as before.
      * Already-concluded (status='final') — a match that already happened
        is a historical record, not a discovery-recency question, so it is
        NEVER excluded by the rolling window; the only thing that can hide
        it is being a synthetic sample fixture (pipeline/sample_data.json,
        classified via _fixture_kind). This closes the match-export gap for
        legacy real matches (e.g. m-cr-zeta-krgf) that predate the Phase B
        automation columns and would otherwise silently vanish from the
        calendar, match directory, tournament pages, team history, search
        and stats despite having real evidence (VODs, map results) on file.
        A bare *unconfirmed upcoming* stub (status != 'final', no
        competition_id/lifecycle_status) is still never fabricated onto the
        calendar — only a concluded match gets this bypass.

    Returns [] on a pre-migration DB that has no discovery columns yet, so
    the public export never crashes on an older DB."""
    cols = {r["name"] for r in con.execute("PRAGMA table_info(matches)")}
    if not {"competition_id", "lifecycle_status"} <= cols:
        return []
    lookback, horizon = _discovery_window_days()
    now = dt.datetime.now(dt.timezone.utc)
    past = (now - dt.timedelta(days=lookback)).date().isoformat()
    future = (now + dt.timedelta(days=horizon)).date().isoformat()
    rows = con.execute(
        """SELECT * FROM matches
           WHERE competition_id IS NOT NULL OR lifecycle_status IS NOT NULL
              OR status='final'
           ORDER BY COALESCE(scheduled_at, finished_at, date), id"""
    ).fetchall()
    out = []
    for m in rows:
        if _fixture_kind(m) == "synthetic":
            continue
        if (m["status"] or "").lower() == "final":
            out.append(m)
            continue
        when = (rv(m, "scheduled_at") or rv(m, "finished_at") or m["date"] or "")[:10]
        if not when:
            out.append(m)
            continue
        if when < past or when > future:
            continue
        out.append(m)
    return out


def _public_match_status(m: Any) -> str:
    """Map the FACEIT lifecycle/content status onto the public vocab
    (upcoming/live/completed/forfeit/cancelled)."""
    lifecycle = (rv(m, "lifecycle_status") or "").lower()
    if lifecycle in ("cancelled", "aborted"):
        return "cancelled"
    if lifecycle == "forfeit":
        return "forfeit"
    if lifecycle == "live":
        return "live"
    if lifecycle == "finished":
        return "completed"
    status = (m["status"] or "").lower()
    return {"upcoming": "upcoming", "live": "live",
            "final": "completed"}.get(status, "upcoming")


def _public_capture_status(m: Any, has_vod: bool, has_maps: bool) -> str | None:
    """Coarse capture state for the public chip. None for cancelled (no
    capture is expected). Vocab matches assets/js/public/core.js CAPTURE_LABELS."""
    lifecycle = (rv(m, "lifecycle_status") or "").lower()
    if lifecycle in ("cancelled", "aborted"):
        return None
    if has_maps:
        return "needs-review"
    if has_vod:
        return "queued"
    return "needs-source"


#: Public match statuses that mean "this match will not be played again".
_MATCH_STATUS_SETTLED = frozenset({"completed", "forfeit", "cancelled"})


def _reconcile_stub_tournament_status(tournaments_by_id: dict,
                                      stub_tids: set,
                                      matches_out: list) -> None:
    """Derive a stub tournament's status from the matches it actually holds.

    A tournament invented from a discovered match has no lifecycle of its own,
    so it is stubbed as "upcoming". Left alone that guess goes stale the moment
    its matches finish, and the site then asserts two contradictory things at
    once — an "UPCOMING" event chip above a full set of final scores. The
    public data's whole claim is that it never states something it cannot
    support, so the guess is reconciled here instead of being rendered.

    Only auto-stubbed tournaments are touched: a curated event carries an
    authoritative status that must win over anything inferred from matches.

    live     - any match in progress
    completed- at least one match played and none still to come
    upcoming - anything else (including an all-cancelled event, which has
               nothing to show and must not claim to be finished)
    """
    if not stub_tids:
        return
    by_tid: dict = {}
    for mo in matches_out:
        by_tid.setdefault(mo.get("tournamentId"), []).append(
            (mo.get("status") or "").lower())

    for tid in stub_tids:
        statuses = by_tid.get(tid) or []
        if not statuses:
            continue
        if "live" in statuses:
            derived = "live"
        elif ("completed" in statuses
              and all(s in _MATCH_STATUS_SETTLED for s in statuses)):
            derived = "completed"
        else:
            derived = "upcoming"
        t = tournaments_by_id[tid]
        t["status"] = derived
        # The lone auto-stubbed stage stands for the whole event, so it must
        # not contradict the parent it was created alongside.
        for stage in t.get("stages") or []:
            stage["status"] = derived


def _fmt_clock(seconds: int | None) -> str | None:
    if seconds is None:
        return None
    s = int(seconds)
    return f"{s // 3600}:{(s % 3600) // 60:02d}:{s % 60:02d}"


